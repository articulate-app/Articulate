import fs from 'node:fs'

function replaceOnce(path, from, to, label) {
  const input = fs.readFileSync(path, 'utf8')
  if (!input.includes(from)) throw new Error(`Patch target not found (${label}) in ${path}`)
  fs.writeFileSync(path, input.replace(from, to))
}
function replaceRegex(path, pattern, to, label) {
  const input = fs.readFileSync(path, 'utf8')
  if (!pattern.test(input)) throw new Error(`Patch regex target not found (${label}) in ${path}`)
  fs.writeFileSync(path, input.replace(pattern, to))
}
