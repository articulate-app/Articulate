create or replace function public.fn_get_owned_content_performance(
  p_project_id integer,
  p_date_from date default null,
  p_date_to date default null
)
returns jsonb
language plpgsql
stable
security invoker
set search_path to 'pg_catalog', 'public'
as $$
declare
  v_gsc_connected boolean;
  v_ga_connected boolean;
  v_gsc jsonb;
  v_ga jsonb;
begin
  if p_project_id is null or not public.can_edit_project(p_project_id) then
    raise exception 'forbidden';
  end if;

  select exists (
    select 1
    from public.project_search_console_properties p
    where p.project_id = p_project_id and p.is_active = true
  ) into v_gsc_connected;

  v_ga_connected := to_regclass('public.project_analytics_properties') is not null
    and exists (
      select 1
      from public.project_analytics_properties p
      where p.project_id = p_project_id and p.is_active = true
    );

  if v_gsc_connected then
    select jsonb_build_object(
      'clicks', sum(clicks),
      'impressions', sum(impressions),
      'ctr', case
        when coalesce(sum(impressions), 0) = 0 then null
        else sum(clicks)::numeric / nullif(sum(impressions), 0)
      end,
      'position_avg', avg(position)
    )
    into v_gsc
    from public.project_search_console_page_query_daily d
    where d.project_id = p_project_id
      and (p_date_from is null or d.metric_date >= p_date_from)
      and (p_date_to is null or d.metric_date <= p_date_to);
  else
    v_gsc := null;
  end if;

  if v_ga_connected and to_regclass('public.project_analytics_pages_daily') is not null then
    begin
      execute $q$
        select jsonb_build_object(
          'page_views', sum(page_views),
          'users', sum(users),
          'sessions', sum(sessions),
          'engaged_sessions', sum(engaged_sessions),
          'engagement_rate', avg(engagement_rate)
        )
        from public.project_analytics_pages_daily d
        where d.project_id = $1
          and ($2::date is null or d.metric_date >= $2)
          and ($3::date is null or d.metric_date <= $3)
      $q$
      into v_ga
      using p_project_id, p_date_from, p_date_to;
    exception
      when undefined_column then
        -- Column names may differ across analytics schema revisions.
        v_ga := jsonb_build_object('note', 'analytics_pages_schema_mismatch');
      when others then
        v_ga := null;
    end;
  else
    v_ga := null;
  end if;

  return jsonb_build_object(
    'project_id', p_project_id,
    'date_from', p_date_from,
    'date_to', p_date_to,
    'search_console_connected', v_gsc_connected,
    'analytics_connected', v_ga_connected,
    'search_console', v_gsc,
    'analytics', v_ga
  );
end;
$$;

