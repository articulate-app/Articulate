create or replace function public.fn_get_project_keyword_gap(
  p_project_id integer,
  p_date_from timestamptz default null,
  p_date_to timestamptz default null,
  p_min_volume integer default 10
)
returns jsonb
language plpgsql
stable
security invoker
set search_path to 'pg_catalog', 'public'
as $$
begin
  if p_project_id is null or not public.can_edit_project(p_project_id) then
    raise exception 'forbidden';
  end if;

  return (
    with article_scope as (
      select a.id, a.entity_type, a.competitor_id
      from public.project_competitive_content_articles a
      where a.project_id = p_project_id
        and a.is_active = true
        and (p_date_from is null or coalesce(a.published_at, a.first_seen_at) >= p_date_from)
        and (p_date_to is null or coalesce(a.published_at, a.first_seen_at) <= p_date_to)
    ),
    keyword_rows as (
      select
        k.normalized_keyword,
        k.keyword,
        k.search_volume,
        k.ranking_position,
        k.entity_type,
        k.article_id,
        a.competitor_id
      from public.project_competitive_article_keywords k
      join article_scope a on a.id = k.article_id
      where k.keyword_type in ('inferred_primary', 'inferred_secondary', 'ranking')
    ),
    by_keyword as (
      select
        normalized_keyword,
        max(keyword) as keyword,
        max(search_volume) filter (where search_volume is not null) as search_volume,
        count(distinct competitor_id) filter (where entity_type = 'competitor')::integer as competitors_count,
        count(*) filter (where entity_type = 'competitor')::integer as competitor_articles_count,
        min(ranking_position) filter (
          where entity_type = 'competitor' and ranking_position is not null
        ) as best_competitor_position,
        count(*) filter (where entity_type = 'owned')::integer as owned_articles_count,
        min(ranking_position) filter (
          where entity_type = 'owned' and ranking_position is not null
        ) as owned_ranking_position
      from keyword_rows
      group by normalized_keyword
    )
    select coalesce(jsonb_agg(
      jsonb_build_object(
        'keyword', keyword,
        'normalized_keyword', normalized_keyword,
        'search_volume', search_volume,
        'competitors_count', competitors_count,
        'competitor_articles_count', competitor_articles_count,
        'best_competitor_position', best_competitor_position,
        'owned_articles_count', owned_articles_count,
        'owned_ranking_position', owned_ranking_position,
        'opportunity_status', case
          when competitors_count = 0 and owned_articles_count = 0 then 'insufficient_data'
          when owned_articles_count = 0 and competitors_count > 0 then 'not_covered'
          when owned_articles_count > 0 and owned_ranking_position is null
            and best_competitor_position is not null then 'covered_not_ranking'
          when owned_ranking_position is not null
            and best_competitor_position is not null
            and owned_ranking_position > best_competitor_position then 'ranking_below_competitors'
          when owned_ranking_position is not null
            and (
              best_competitor_position is null
              or owned_ranking_position <= best_competitor_position
            ) then 'owned_advantage'
          else 'insufficient_data'
        end
      )
      order by coalesce(search_volume, 0) desc, competitors_count desc, keyword
    ), '[]'::jsonb)
    from by_keyword
    where competitors_count > 0
      and (search_volume is null or search_volume >= coalesce(p_min_volume, 10))
  );
end;
$$;

