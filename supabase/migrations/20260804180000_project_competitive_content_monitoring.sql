create or replace view public.v_project_competitive_content_entities
with (security_invoker = true)
as
select
  p.id as project_id,
  ('owned:' || p.id::text) as entity_id,
  coalesce(nullif(trim(p.name), ''), 'Our brand') as entity_name,
  'owned'::text as entity_type,
  true as is_owned,
  null::bigint as competitor_id
from public.projects p
where coalesce(p.is_deleted, false) = false
  and coalesce(p.active, true) = true

union all

select
  c.project_id,
  ('competitor:' || c.id::text) as entity_id,
  c.name as entity_name,
  'competitor'::text as entity_type,
  false as is_owned,
  c.id as competitor_id
from public.project_competitors c
where c.is_active = true;

create or replace view public.v_project_competitive_content_articles
with (security_invoker = true)
as
select
  a.id,
  a.project_id,
  a.website_id,
  a.content_source_id,
  a.entity_type,
  a.competitor_id,
  case
    when a.entity_type = 'owned' then ('owned:' || a.project_id::text)
    else ('competitor:' || a.competitor_id::text)
  end as entity_id,
  case
    when a.entity_type = 'owned' then coalesce(nullif(trim(p.name), ''), 'Our brand')
    else c.name
  end as entity_name,
  (a.entity_type = 'owned') as is_owned,
  a.url,
  a.canonical_url,
  a.title,
  a.description,
  a.author,
  a.language_code,
  a.published_at,
  a.modified_at,
  a.image_url,
  a.page_type,
  a.summary,
  a.markdown_excerpt,
  a.content_hash,
  a.schema_types,
  a.translation_group_id,
  a.primary_keyword,
  a.is_active,
  a.first_seen_at,
  a.last_seen_at,
  a.scraped_at,
  a.keywords_extracted_at,
  a.ranking_synced_at,
  a.created_at,
  a.updated_at,
  s.source_url as content_source_url,
  s.source_type as content_source_type,
  s.language_code as content_source_language,
  w.root_url as website_root_url,
  w.normalized_domain as website_domain
from public.project_competitive_content_articles a
join public.projects p on p.id = a.project_id
left join public.project_competitors c on c.id = a.competitor_id
left join public.project_competitive_content_sources s on s.id = a.content_source_id
left join public.project_competitive_websites w on w.id = a.website_id;

