create or replace function public.fn_get_project_competitive_content_summary(
  p_project_id integer,
  p_date_from timestamptz default null,
  p_date_to timestamptz default null,
  p_entity_ids text[] default null,
  p_language_codes text[] default null,
  p_source_types text[] default null
)
returns jsonb
language plpgsql
stable
security invoker
set search_path to 'pg_catalog', 'public'
as $$
declare
  v_result jsonb;
  v_days numeric;
begin
  if p_project_id is null or not public.can_edit_project(p_project_id) then
    raise exception 'forbidden';
  end if;

  v_days := greatest(
    1,
    extract(epoch from (coalesce(p_date_to, now()) - coalesce(p_date_from, now() - interval '30 days'))) / 86400.0
  );

  with entities as (
    select *
    from public.v_project_competitive_content_entities e
    where e.project_id = p_project_id
      and (p_entity_ids is null or cardinality(p_entity_ids) = 0 or e.entity_id = any (p_entity_ids))
  ),
  filtered as (
    select v.*
    from public.v_project_competitive_content_articles v
    where v.project_id = p_project_id
      and v.is_active = true
      and (p_date_from is null or coalesce(v.published_at, v.first_seen_at) >= p_date_from)
      and (p_date_to is null or coalesce(v.published_at, v.first_seen_at) <= p_date_to)
      and (p_entity_ids is null or cardinality(p_entity_ids) = 0 or v.entity_id = any (p_entity_ids))
      and (p_language_codes is null or cardinality(p_language_codes) = 0 or v.language_code = any (p_language_codes))
      and (p_source_types is null or cardinality(p_source_types) = 0 or v.content_source_type = any (p_source_types))
  ),
  entity_stats as (
    select
      e.entity_id,
      e.entity_name,
      e.entity_type,
      e.is_owned,
      count(f.id)::integer as articles_count,
      count(distinct f.language_code) filter (where f.language_code is not null)::integer as languages_count,
      count(distinct f.content_source_id) filter (where f.content_source_id is not null)::integer as sources_count,
      max(coalesce(f.published_at, f.first_seen_at)) as last_published_at,
      (
        select count(distinct k.normalized_keyword)::integer
        from public.project_competitive_article_keywords k
        join filtered f2 on f2.id = k.article_id
        where f2.entity_id = e.entity_id
          and k.keyword_type in ('inferred_primary', 'inferred_secondary')
      ) as unique_keywords,
      (
        select coalesce(sum(k.search_volume), 0)::bigint
        from public.project_competitive_article_keywords k
        join filtered f2 on f2.id = k.article_id
        where f2.entity_id = e.entity_id
          and k.keyword_type = 'inferred_primary'
          and k.search_volume is not null
      ) as keyword_volume_total,
      (
        select count(*)::integer
        from public.project_competitive_article_keywords k
        join filtered f2 on f2.id = k.article_id
        where f2.entity_id = e.entity_id
          and k.keyword_type = 'ranking'
          and k.ranking_position is not null
      ) as ranking_keywords_count,
      (
        select avg(k.ranking_position)
        from public.project_competitive_article_keywords k
        join filtered f2 on f2.id = k.article_id
        where f2.entity_id = e.entity_id
          and k.keyword_type = 'ranking'
          and k.ranking_position is not null
      ) as ranking_position_avg
    from entities e
    left join filtered f on f.entity_id = e.entity_id
    group by e.entity_id, e.entity_name, e.entity_type, e.is_owned
  ),
  language_dist as (
    select
      f.entity_id,
      jsonb_object_agg(coalesce(f.language_code, 'unknown'), cnt) as by_language
    from (
      select entity_id, language_code, count(*)::integer as cnt
      from filtered
      group by entity_id, language_code
    ) f
    group by f.entity_id
  ),
  source_dist as (
    select
      f.entity_id,
      jsonb_object_agg(coalesce(f.content_source_type, 'other'), cnt) as by_source_type
    from (
      select entity_id, content_source_type, count(*)::integer as cnt
      from filtered
      group by entity_id, content_source_type
    ) f
    group by f.entity_id
  ),
  weekly as (
    select
      f.entity_id,
      date_trunc('week', coalesce(f.published_at, f.first_seen_at))::date as week_start,
      count(*)::integer as articles_count
    from filtered f
    where coalesce(f.published_at, f.first_seen_at) is not null
    group by f.entity_id, date_trunc('week', coalesce(f.published_at, f.first_seen_at))
  ),
  weekly_agg as (
    select
      entity_id,
      jsonb_agg(
        jsonb_build_object('week_start', week_start, 'articles_count', articles_count)
        order by week_start
      ) as series
    from weekly
    group by entity_id
  ),
  top_articles as (
    select
      x.entity_id,
      jsonb_agg(
        jsonb_build_object(
          'id', x.id,
          'title', x.title,
          'url', x.url,
          'published_at', x.published_at,
          'primary_keyword', x.primary_keyword,
          'image_url', x.image_url
        )
        order by coalesce(x.published_at, x.first_seen_at) desc nulls last
      ) as articles
    from (
      select
        f.*,
        row_number() over (
          partition by f.entity_id
          order by coalesce(f.published_at, f.first_seen_at) desc nulls last
        ) as rn
      from filtered f
    ) x
    where x.rn <= 5
    group by x.entity_id
  ),
  totals as (
    select
      coalesce(sum(articles_count), 0)::integer as articles_count,
      count(*)::integer as entities_count
    from entity_stats
  )
  select jsonb_build_object(
    'project_id', p_project_id,
    'date_from', p_date_from,
    'date_to', p_date_to,
    'period_days', v_days,
    'totals', jsonb_build_object(
      'articles_count', t.articles_count,
      'entities_count', t.entities_count
    ),
    'entities', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'entity_id', es.entity_id,
          'entity_name', es.entity_name,
          'entity_type', es.entity_type,
          'is_owned', es.is_owned,
          'articles_count', es.articles_count,
          'articles_per_week', case
            when es.articles_count = 0 then 0
            else round((es.articles_count::numeric / (v_days / 7.0))::numeric, 2)
          end,
          'articles_per_month', case
            when es.articles_count = 0 then 0
            else round((es.articles_count::numeric / (v_days / 30.0))::numeric, 2)
          end,
          'days_since_last_publish', case
            when es.last_published_at is null then null
            else floor(extract(epoch from (now() - es.last_published_at)) / 86400.0)::integer
          end,
          'languages_count', es.languages_count,
          'sources_count', es.sources_count,
          'unique_keywords', coalesce(es.unique_keywords, 0),
          'keyword_volume_total', es.keyword_volume_total,
          'ranking_keywords_count', coalesce(es.ranking_keywords_count, 0),
          'ranking_position_avg', es.ranking_position_avg,
          'share_of_articles_pct', case
            when t.articles_count = 0 then null
            else round((es.articles_count::numeric * 100.0 / t.articles_count)::numeric, 1)
          end,
          'by_language', coalesce(ld.by_language, '{}'::jsonb),
          'by_source_type', coalesce(sd.by_source_type, '{}'::jsonb),
          'weekly_series', coalesce(wa.series, '[]'::jsonb),
          'top_articles', coalesce(ta.articles, '[]'::jsonb)
        )
        order by es.is_owned desc, es.articles_count desc, es.entity_name
      )
      from entity_stats es
      left join language_dist ld on ld.entity_id = es.entity_id
      left join source_dist sd on sd.entity_id = es.entity_id
      left join weekly_agg wa on wa.entity_id = es.entity_id
      left join top_articles ta on ta.entity_id = es.entity_id
    ), '[]'::jsonb)
  )
  into v_result
  from totals t;

  return v_result;
end;
$$;

