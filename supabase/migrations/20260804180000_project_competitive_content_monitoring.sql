-- Competitive content monitoring: websites → editorial sources → articles → keywords.
-- Owned brand identity is derived from projects (never from competitor rows).
-- Does NOT reuse project_site_pages (owned RAG/internal-link catalogue).
-- Idempotent: safe if partially applied.

-- ---------------------------------------------------------------------------
-- 1) Websites (owned + competitor)
-- ---------------------------------------------------------------------------

create table if not exists public.project_competitive_websites (
  id bigint generated by default as identity primary key,
  project_id integer not null references public.projects(id) on delete cascade,
  entity_type text not null,
  competitor_id bigint null references public.project_competitors(id) on delete cascade,
  root_url text not null,
  normalized_domain text not null,
  market_code text null,
  default_language_code text null,
  include_subdomains boolean not null default false,
  is_active boolean not null default true,
  last_discovered_at timestamptz null,
  last_synced_at timestamptz null,
  last_sync_status text null,
  last_sync_error text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_competitive_websites_entity_type_check check (
    entity_type in ('owned', 'competitor')
  ),
  constraint project_competitive_websites_entity_check check (
    (
      entity_type = 'owned'
      and competitor_id is null
    )
    or (
      entity_type = 'competitor'
      and competitor_id is not null
    )
  ),
  constraint project_competitive_websites_status_check check (
    last_sync_status is null
    or last_sync_status in ('queued', 'running', 'succeeded', 'failed', 'partial')
  ),
  constraint project_competitive_websites_root_url_check check (
    char_length(trim(root_url)) > 0
  ),
  constraint project_competitive_websites_domain_check check (
    char_length(trim(normalized_domain)) > 0
  )
);

create unique index if not exists project_competitive_websites_owned_domain_unique
  on public.project_competitive_websites(project_id, normalized_domain)
  where entity_type = 'owned';

create unique index if not exists project_competitive_websites_competitor_domain_unique
  on public.project_competitive_websites(competitor_id, normalized_domain)
  where entity_type = 'competitor' and competitor_id is not null;

create index if not exists idx_project_competitive_websites_project
  on public.project_competitive_websites(project_id, is_active);

create index if not exists idx_project_competitive_websites_competitor
  on public.project_competitive_websites(competitor_id)
  where competitor_id is not null;

