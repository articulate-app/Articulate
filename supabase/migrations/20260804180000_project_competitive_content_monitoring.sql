create or replace function public.fn_list_project_competitive_articles(
  p_project_id integer,
  p_date_from timestamptz default null,
  p_date_to timestamptz default null,
  p_entity_ids text[] default null,
  p_language_codes text[] default null,
  p_source_types text[] default null,
  p_keywords text[] default null,
  p_has_ranking boolean default null,
  p_limit integer default 100,
  p_offset integer default 0
)
returns setof public.v_project_competitive_content_articles
language plpgsql
stable
security invoker
set search_path to 'pg_catalog', 'public'
as $$
begin
  if p_project_id is null or not public.can_edit_project(p_project_id) then
    raise exception 'forbidden';
  end if;

  return query
  select v.*
  from public.v_project_competitive_content_articles v
  where v.project_id = p_project_id
    and v.is_active = true
    and (p_date_from is null or v.published_at >= p_date_from or (v.published_at is null and v.first_seen_at >= p_date_from))
    and (p_date_to is null or v.published_at <= p_date_to or (v.published_at is null and v.first_seen_at <= p_date_to))
    and (p_entity_ids is null or cardinality(p_entity_ids) = 0 or v.entity_id = any (p_entity_ids))
    and (p_language_codes is null or cardinality(p_language_codes) = 0 or v.language_code = any (p_language_codes))
    and (p_source_types is null or cardinality(p_source_types) = 0 or v.content_source_type = any (p_source_types))
    and (
      p_keywords is null
      or cardinality(p_keywords) = 0
      or exists (
        select 1
        from public.project_competitive_article_keywords k
        where k.article_id = v.id
          and k.normalized_keyword = any (
            select lower(trim(x)) from unnest(p_keywords) as x
          )
      )
      or lower(coalesce(v.primary_keyword, '')) = any (
        select lower(trim(x)) from unnest(p_keywords) as x
      )
    )
    and (
      p_has_ranking is null
      or (
        p_has_ranking = true
        and exists (
          select 1
          from public.project_competitive_article_keywords k
          where k.article_id = v.id
            and k.keyword_type = 'ranking'
            and k.ranking_position is not null
        )
      )
      or (
        p_has_ranking = false
        and not exists (
          select 1
          from public.project_competitive_article_keywords k
          where k.article_id = v.id
            and k.keyword_type = 'ranking'
            and k.ranking_position is not null
        )
      )
    )
  order by coalesce(v.published_at, v.first_seen_at) desc nulls last
  limit greatest(1, least(coalesce(p_limit, 100), 500))
  offset greatest(0, coalesce(p_offset, 0));
end;
$$;

