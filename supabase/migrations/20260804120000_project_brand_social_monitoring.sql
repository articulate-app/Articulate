-- ---------------------------------------------------------------------------
-- 7) List posts RPC (unified, filterable)
-- ---------------------------------------------------------------------------

create or replace function public.fn_list_project_social_posts(
  p_project_id integer,
  p_date_from timestamptz default null,
  p_date_to timestamptz default null,
  p_networks text[] default null,
  p_entity_ids text[] default null,
  p_media_types text[] default null,
  p_limit integer default 100
)
returns setof public.v_project_social_posts
language plpgsql
stable
security invoker
set search_path to 'pg_catalog', 'public'
as $$
begin
  if p_project_id is null or not public.can_edit_project(p_project_id) then
    raise exception 'forbidden';
  end if;

  return query
  select v.*
  from public.v_project_social_posts v
  where v.project_id = p_project_id
    and (p_date_from is null or v.published_at >= p_date_from)
    and (p_date_to is null or v.published_at <= p_date_to)
    and (p_networks is null or cardinality(p_networks) = 0 or v.network = any (p_networks))
    and (p_entity_ids is null or cardinality(p_entity_ids) = 0 or v.entity_id = any (p_entity_ids))
    and (
      p_media_types is null
      or cardinality(p_media_types) = 0
      or coalesce(v.media_type, 'unknown') = any (p_media_types)
    )
  order by v.published_at desc nulls last, v.id desc
  limit greatest(1, least(coalesce(p_limit, 100), 500));
end;
$$;

revoke all on function public.fn_list_project_social_posts(
  integer, timestamptz, timestamptz, text[], text[], text[], integer
) from public;
grant execute on function public.fn_list_project_social_posts(
  integer, timestamptz, timestamptz, text[], text[], text[], integer
) to authenticated;
grant execute on function public.fn_list_project_social_posts(
  integer, timestamptz, timestamptz, text[], text[], text[], integer
) to service_role;
