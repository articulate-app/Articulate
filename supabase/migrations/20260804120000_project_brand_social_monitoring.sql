-- Phase 1: owned brand social profiles + unified social posts layer.
-- Does not recreate competitor monitoring; extends it.

-- ---------------------------------------------------------------------------
-- 1) Brand (owned) social profiles
-- ---------------------------------------------------------------------------

create table if not exists public.project_brand_social_profiles (
  id bigint generated by default as identity primary key,
  project_id integer not null references public.projects(id) on delete cascade,
  network text not null,
  profile_url text not null,
  profile_url_normalized text not null,
  external_profile_id text null,
  is_active boolean not null default true,
  last_synced_at timestamptz null,
  last_sync_status text null,
  last_sync_error text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_brand_social_profiles_network_check check (
    network in ('linkedin', 'instagram', 'facebook', 'youtube', 'tiktok', 'x')
  ),
  constraint project_brand_social_profiles_status_check check (
    last_sync_status is null
    or last_sync_status in ('queued', 'running', 'succeeded', 'failed', 'partial')
  ),
  constraint project_brand_social_profiles_url_not_blank check (
    char_length(trim(profile_url)) > 0
  ),
  constraint project_brand_social_profiles_unique_profile
    unique (project_id, network, profile_url_normalized)
);

create index if not exists idx_project_brand_social_profiles_project
  on public.project_brand_social_profiles(project_id, is_active);

create index if not exists idx_project_brand_social_profiles_sync
  on public.project_brand_social_profiles(is_active, last_synced_at)
  where is_active = true;

-- ---------------------------------------------------------------------------
-- 2) Generalize competitor posts to support owned posts
-- ---------------------------------------------------------------------------

alter table public.project_competitor_social_posts
  add column if not exists entity_type text;

alter table public.project_competitor_social_posts
  add column if not exists brand_social_profile_id bigint null
    references public.project_brand_social_profiles(id) on delete cascade;

-- Backfill existing rows as competitor posts.
update public.project_competitor_social_posts
set entity_type = 'competitor'
where entity_type is null;

alter table public.project_competitor_social_posts
  alter column entity_type set default 'competitor';

alter table public.project_competitor_social_posts
  alter column entity_type set not null;

-- Allow owned posts (no competitor).
alter table public.project_competitor_social_posts
  alter column competitor_id drop not null;

alter table public.project_competitor_social_posts
  alter column social_profile_id drop not null;

alter table public.project_competitor_social_posts
  drop constraint if exists project_competitor_social_posts_entity_check;

alter table public.project_competitor_social_posts
  add constraint project_competitor_social_posts_entity_check check (
    (
      entity_type = 'competitor'
      and competitor_id is not null
      and social_profile_id is not null
      and brand_social_profile_id is null
    )
    or (
      entity_type = 'owned'
      and brand_social_profile_id is not null
      and competitor_id is null
      and social_profile_id is null
    )
  );

alter table public.project_competitor_social_posts
  drop constraint if exists project_competitor_social_posts_entity_type_check;

alter table public.project_competitor_social_posts
  add constraint project_competitor_social_posts_entity_type_check check (
    entity_type in ('owned', 'competitor')
  );

-- Dedupe for owned posts (competitor unique already exists on social_profile_id + dedupe_key).
create unique index if not exists project_competitor_social_posts_owned_dedupe
  on public.project_competitor_social_posts(brand_social_profile_id, dedupe_key)
  where entity_type = 'owned' and brand_social_profile_id is not null;

create index if not exists idx_project_social_posts_entity_published
  on public.project_competitor_social_posts(project_id, entity_type, published_at desc nulls last);

create index if not exists idx_project_social_posts_network_external
  on public.project_competitor_social_posts(project_id, network, external_post_id)
  where external_post_id is not null;

create index if not exists idx_project_social_posts_brand_profile
  on public.project_competitor_social_posts(brand_social_profile_id, published_at desc nulls last)
  where brand_social_profile_id is not null;

