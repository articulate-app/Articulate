-- ---------------------------------------------------------------------------
-- 4) Daily follower/posts snapshots (owned + competitor)
-- ---------------------------------------------------------------------------

create table if not exists public.project_social_profile_daily_snapshots (
  id bigint generated by default as identity primary key,
  project_id integer not null references public.projects(id) on delete cascade,
  entity_type text not null,
  brand_social_profile_id bigint null
    references public.project_brand_social_profiles(id) on delete cascade,
  competitor_social_profile_id bigint null
    references public.project_competitor_social_profiles(id) on delete cascade,
  snapshot_date date not null,
  followers_count integer null,
  posts_count integer null,
  raw_payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint project_social_profile_daily_snapshots_entity_type_check check (
    entity_type in ('owned', 'competitor')
  ),
  constraint project_social_profile_daily_snapshots_entity_check check (
    (
      entity_type = 'owned'
      and brand_social_profile_id is not null
      and competitor_social_profile_id is null
    )
    or (
      entity_type = 'competitor'
      and competitor_social_profile_id is not null
      and brand_social_profile_id is null
    )
  )
);

create unique index if not exists project_social_snapshots_owned_unique
  on public.project_social_profile_daily_snapshots(brand_social_profile_id, snapshot_date)
  where entity_type = 'owned' and brand_social_profile_id is not null;

create unique index if not exists project_social_snapshots_competitor_unique
  on public.project_social_profile_daily_snapshots(competitor_social_profile_id, snapshot_date)
  where entity_type = 'competitor' and competitor_social_profile_id is not null;

create index if not exists idx_project_social_snapshots_project_date
  on public.project_social_profile_daily_snapshots(project_id, snapshot_date desc);

-- ---------------------------------------------------------------------------
-- 5) Unified views
-- ---------------------------------------------------------------------------

create or replace view public.v_project_social_entities
with (security_invoker = true)
as
select
  p.id as project_id,
  ('owned:' || p.id::text) as entity_id,
  coalesce(nullif(trim(p.name), ''), 'Our brand') as entity_name,
  'owned'::text as entity_type,
  true as is_owned
from public.projects p
where coalesce(p.is_deleted, false) = false
  and coalesce(p.active, true) = true

union all

select
  c.project_id,
  ('competitor:' || c.id::text) as entity_id,
  c.name as entity_name,
  'competitor'::text as entity_type,
  false as is_owned
from public.project_competitors c
where c.is_active = true;

create or replace view public.v_project_social_posts
with (security_invoker = true)
as
select
  posts.id,
  posts.project_id,
  case
    when posts.entity_type = 'owned' then ('owned:' || posts.project_id::text)
    else ('competitor:' || posts.competitor_id::text)
  end as entity_id,
  posts.entity_type,
  (posts.entity_type = 'owned') as is_owned,
  case
    when posts.entity_type = 'owned' then coalesce(nullif(trim(proj.name), ''), 'Our brand')
    else c.name
  end as entity_name,
  posts.network,
  posts.external_post_id,
  posts.post_url,
  posts.published_at,
  posts.text_content,
  posts.media_type,
  posts.media_urls,
  posts.thumbnail_url,
  posts.reactions_count,
  posts.comments_count,
  posts.shares_count,
  posts.views_count,
  posts.followers_count_at_sync,
  posts.extra_metrics,
  posts.last_seen_at,
  posts.created_at,
  posts.updated_at,
  posts.competitor_id,
  posts.social_profile_id,
  posts.brand_social_profile_id,
  posts.dedupe_key
from public.project_competitor_social_posts posts
left join public.projects proj
  on proj.id = posts.project_id
left join public.project_competitors c
  on c.id = posts.competitor_id;

