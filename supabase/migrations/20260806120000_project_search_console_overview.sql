create or replace function public.fn_get_project_search_overview(
  p_project_id integer,
  p_date_from date default null,
  p_date_to date default null,
  p_compare_date_from date default null,
  p_compare_date_to date default null,
  p_search_type text default 'web',
  p_limit integer default 10
)
returns jsonb
language plpgsql
stable
security invoker
set search_path to 'pg_catalog', 'public'
as $$
declare
  v_limit integer := least(greatest(coalesce(p_limit, 10), 1), 50);
  v_search_type text := coalesce(nullif(trim(p_search_type), ''), 'web');
  v_connected boolean;
  v_property jsonb;
  v_current jsonb;
  v_previous jsonb;
  v_timeseries jsonb;
  v_queries jsonb;
  v_pages jsonb;
  v_opportunities jsonb;
  v_indexation jsonb;
  v_has_property_daily boolean;
  v_latest_metric_date date;
  v_last_synced_at timestamptz;
begin
  if p_project_id is null or not public.can_edit_project(p_project_id) then
    raise exception 'forbidden';
  end if;

  select exists (
    select 1
    from public.project_search_console_properties p
    where p.project_id = p_project_id and p.is_active = true
  )
  into v_connected;

  select jsonb_build_object(
    'id', p.id,
    'property_url', p.property_url,
    'site_type', p.site_type,
    'last_synced_at', p.last_synced_at,
    'last_sync_status', p.last_sync_status,
    'last_sync_error', p.last_sync_error,
    'earliest_metric_date', p.earliest_metric_date,
    'latest_metric_date', p.latest_metric_date,
    'backfill_status', p.backfill_status
  ),
  p.last_synced_at,
  p.latest_metric_date
  into v_property, v_last_synced_at, v_latest_metric_date
  from public.project_search_console_properties p
  where p.project_id = p_project_id
    and p.is_active = true
  order by p.updated_at desc
  limit 1;

  select exists (
    select 1
    from public.project_search_console_property_daily d
    where d.project_id = p_project_id
      and d.search_type = v_search_type
      and d.country = ''
      and d.device = ''
      and (p_date_from is null or d.metric_date >= p_date_from)
      and (p_date_to is null or d.metric_date <= p_date_to)
    limit 1
  )
  into v_has_property_daily;

  if v_has_property_daily then
    select public.fn_gsc_metric_bundle(
      sum(d.clicks)::numeric,
      sum(d.impressions)::numeric,
      sum(coalesce(d.position, 0) * coalesce(d.impressions, 0))::numeric
    )
    into v_current
    from public.project_search_console_property_daily d
    where d.project_id = p_project_id
      and d.search_type = v_search_type
      and d.country = ''
      and d.device = ''
      and (p_date_from is null or d.metric_date >= p_date_from)
      and (p_date_to is null or d.metric_date <= p_date_to);

    if p_compare_date_from is not null and p_compare_date_to is not null then
      select public.fn_gsc_metric_bundle(
        sum(d.clicks)::numeric,
        sum(d.impressions)::numeric,
        sum(coalesce(d.position, 0) * coalesce(d.impressions, 0))::numeric
      )
      into v_previous
      from public.project_search_console_property_daily d
      where d.project_id = p_project_id
        and d.search_type = v_search_type
        and d.country = ''
        and d.device = ''
        and d.metric_date >= p_compare_date_from
        and d.metric_date <= p_compare_date_to;
    end if;

    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'date', t.metric_date,
          'clicks', t.clicks,
          'impressions', t.impressions,
          'ctr', t.ctr,
          'position_avg', t.position_avg
        )
        order by t.metric_date
      ),
      '[]'::jsonb
    )
    into v_timeseries
    from (
      select
        d.metric_date,
        coalesce(sum(d.clicks), 0)::bigint as clicks,
        coalesce(sum(d.impressions), 0)::bigint as impressions,
        case
          when coalesce(sum(d.impressions), 0) = 0 then null
          else sum(d.clicks)::numeric / nullif(sum(d.impressions), 0)
        end as ctr,
        case
          when coalesce(sum(d.impressions), 0) = 0 then null
          else sum(coalesce(d.position, 0) * coalesce(d.impressions, 0))
               / nullif(sum(d.impressions), 0)
        end as position_avg
      from public.project_search_console_property_daily d
      where d.project_id = p_project_id
        and d.search_type = v_search_type
        and d.country = ''
        and d.device = ''
        and (p_date_from is null or d.metric_date >= p_date_from)
        and (p_date_to is null or d.metric_date <= p_date_to)
      group by d.metric_date
    ) t;
  else
    -- Fallback to page×query daily while property aggregates are empty
    select public.fn_gsc_metric_bundle(
      sum(d.clicks)::numeric,
      sum(d.impressions)::numeric,
      sum(coalesce(d.position, 0) * coalesce(d.impressions, 0))::numeric
    )
    into v_current
    from public.project_search_console_page_query_daily d
    where d.project_id = p_project_id
      and coalesce(d.search_type, 'web') = v_search_type
      and (p_date_from is null or d.metric_date >= p_date_from)
      and (p_date_to is null or d.metric_date <= p_date_to);

    if p_compare_date_from is not null and p_compare_date_to is not null then
      select public.fn_gsc_metric_bundle(
        sum(d.clicks)::numeric,
        sum(d.impressions)::numeric,
        sum(coalesce(d.position, 0) * coalesce(d.impressions, 0))::numeric
      )
      into v_previous
      from public.project_search_console_page_query_daily d
      where d.project_id = p_project_id
        and coalesce(d.search_type, 'web') = v_search_type
        and d.metric_date >= p_compare_date_from
        and d.metric_date <= p_compare_date_to;
    end if;

    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'date', t.metric_date,
          'clicks', t.clicks,
          'impressions', t.impressions,
          'ctr', t.ctr,
          'position_avg', t.position_avg
        )
        order by t.metric_date
      ),
      '[]'::jsonb
    )
    into v_timeseries
    from (
      select
        d.metric_date,
        coalesce(sum(d.clicks), 0)::bigint as clicks,
        coalesce(sum(d.impressions), 0)::bigint as impressions,
        case
          when coalesce(sum(d.impressions), 0) = 0 then null
          else sum(d.clicks)::numeric / nullif(sum(d.impressions), 0)
        end as ctr,
        case
          when coalesce(sum(d.impressions), 0) = 0 then null
          else sum(coalesce(d.position, 0) * coalesce(d.impressions, 0))
               / nullif(sum(d.impressions), 0)
        end as position_avg
      from public.project_search_console_page_query_daily d
      where d.project_id = p_project_id
        and coalesce(d.search_type, 'web') = v_search_type
        and (p_date_from is null or d.metric_date >= p_date_from)
        and (p_date_to is null or d.metric_date <= p_date_to)
      group by d.metric_date
    ) t;
  end if;

  -- Top queries (prefer query_daily)
  if exists (
    select 1 from public.project_search_console_query_daily q
    where q.project_id = p_project_id
      and q.search_type = v_search_type
      and (p_date_from is null or q.metric_date >= p_date_from)
      and (p_date_to is null or q.metric_date <= p_date_to)
    limit 1
  ) then
    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'query', r.query,
          'clicks', r.clicks,
          'impressions', r.impressions,
          'ctr', r.ctr,
          'position_avg', r.position_avg
        )
        order by r.clicks desc, r.impressions desc
      ),
      '[]'::jsonb
    )
    into v_queries
    from (
      select
        q.query,
        coalesce(sum(q.clicks), 0)::bigint as clicks,
        coalesce(sum(q.impressions), 0)::bigint as impressions,
        case
          when coalesce(sum(q.impressions), 0) = 0 then null
          else sum(q.clicks)::numeric / nullif(sum(q.impressions), 0)
        end as ctr,
        case
          when coalesce(sum(q.impressions), 0) = 0 then null
          else sum(coalesce(q.position, 0) * coalesce(q.impressions, 0))
               / nullif(sum(q.impressions), 0)
        end as position_avg
      from public.project_search_console_query_daily q
      where q.project_id = p_project_id
        and q.search_type = v_search_type
        and q.country = ''
        and q.device = ''
        and (p_date_from is null or q.metric_date >= p_date_from)
        and (p_date_to is null or q.metric_date <= p_date_to)
      group by q.query
      order by sum(q.clicks) desc nulls last, sum(q.impressions) desc nulls last
      limit v_limit
    ) r;
  else
    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'query', r.label,
          'clicks', r.clicks,
          'impressions', r.impressions,
          'ctr', r.ctr,
          'position_avg', r.position_avg
        )
        order by r.clicks desc, r.impressions desc
      ),
      '[]'::jsonb
    )
    into v_queries
    from (
      select
        d.query as label,
        coalesce(sum(d.clicks), 0)::bigint as clicks,
        coalesce(sum(d.impressions), 0)::bigint as impressions,
        case
          when coalesce(sum(d.impressions), 0) = 0 then null
          else sum(d.clicks)::numeric / nullif(sum(d.impressions), 0)
        end as ctr,
        case
          when coalesce(sum(d.impressions), 0) = 0 then null
          else sum(coalesce(d.position, 0) * coalesce(d.impressions, 0))
               / nullif(sum(d.impressions), 0)
        end as position_avg
      from public.project_search_console_page_query_daily d
      where d.project_id = p_project_id
        and coalesce(d.search_type, 'web') = v_search_type
        and (p_date_from is null or d.metric_date >= p_date_from)
        and (p_date_to is null or d.metric_date <= p_date_to)
      group by d.query
      order by sum(d.clicks) desc nulls last, sum(d.impressions) desc nulls last
      limit v_limit
    ) r;
  end if;

  -- Top pages
  if exists (
    select 1 from public.project_search_console_page_daily p
    where p.project_id = p_project_id
      and p.search_type = v_search_type
      and (p_date_from is null or p.metric_date >= p_date_from)
      and (p_date_to is null or p.metric_date <= p_date_to)
    limit 1
  ) then
    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'page', r.page_label,
          'clicks', r.clicks,
          'impressions', r.impressions,
          'ctr', r.ctr,
          'position_avg', r.position_avg
        )
        order by r.clicks desc, r.impressions desc
      ),
      '[]'::jsonb
    )
    into v_pages
    from (
      select
        coalesce(p.canonical_url, p.page_url) as page_label,
        coalesce(sum(p.clicks), 0)::bigint as clicks,
        coalesce(sum(p.impressions), 0)::bigint as impressions,
        case
          when coalesce(sum(p.impressions), 0) = 0 then null
          else sum(p.clicks)::numeric / nullif(sum(p.impressions), 0)
        end as ctr,
        case
          when coalesce(sum(p.impressions), 0) = 0 then null
          else sum(coalesce(p.position, 0) * coalesce(p.impressions, 0))
               / nullif(sum(p.impressions), 0)
        end as position_avg
      from public.project_search_console_page_daily p
      where p.project_id = p_project_id
        and p.search_type = v_search_type
        and p.country = ''
        and p.device = ''
        and (p_date_from is null or p.metric_date >= p_date_from)
        and (p_date_to is null or p.metric_date <= p_date_to)
      group by coalesce(p.canonical_url, p.page_url)
      order by sum(p.clicks) desc nulls last, sum(p.impressions) desc nulls last
      limit v_limit
    ) r;
  else
    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'page', r.page_label,
          'clicks', r.clicks,
          'impressions', r.impressions,
          'ctr', r.ctr,
          'position_avg', r.position_avg
        )
        order by r.clicks desc, r.impressions desc
      ),
      '[]'::jsonb
    )
    into v_pages
    from (
      select
        coalesce(d.canonical_url, d.page_url) as page_label,
        coalesce(sum(d.clicks), 0)::bigint as clicks,
        coalesce(sum(d.impressions), 0)::bigint as impressions,
        case
          when coalesce(sum(d.impressions), 0) = 0 then null
          else sum(d.clicks)::numeric / nullif(sum(d.impressions), 0)
        end as ctr,
        case
          when coalesce(sum(d.impressions), 0) = 0 then null
          else sum(coalesce(d.position, 0) * coalesce(d.impressions, 0))
               / nullif(sum(d.impressions), 0)
        end as position_avg
      from public.project_search_console_page_query_daily d
      where d.project_id = p_project_id
        and coalesce(d.search_type, 'web') = v_search_type
        and (p_date_from is null or d.metric_date >= p_date_from)
        and (p_date_to is null or d.metric_date <= p_date_to)
      group by coalesce(d.canonical_url, d.page_url)
      order by sum(d.clicks) desc nulls last, sum(d.impressions) desc nulls last
      limit v_limit
    ) r;
  end if;

  -- Opportunities from query aggregates (high impressions, low CTR / positions 4-20)
  select jsonb_build_object(
    'high_impressions_low_ctr', coalesce((
      select jsonb_agg(x order by x.impressions desc)
      from (
        select
          q.query,
          coalesce(sum(q.clicks), 0)::bigint as clicks,
          coalesce(sum(q.impressions), 0)::bigint as impressions,
          case
            when coalesce(sum(q.impressions), 0) = 0 then null
            else sum(q.clicks)::numeric / nullif(sum(q.impressions), 0)
          end as ctr,
          case
            when coalesce(sum(q.impressions), 0) = 0 then null
            else sum(coalesce(q.position, 0) * coalesce(q.impressions, 0))
                 / nullif(sum(q.impressions), 0)
          end as position_avg
        from public.project_search_console_query_daily q
        where q.project_id = p_project_id
          and q.search_type = v_search_type
          and q.country = ''
          and q.device = ''
          and (p_date_from is null or q.metric_date >= p_date_from)
          and (p_date_to is null or q.metric_date <= p_date_to)
        group by q.query
        having coalesce(sum(q.impressions), 0) >= 100
           and (
             coalesce(sum(q.clicks), 0)::numeric
             / nullif(sum(q.impressions), 0)
           ) < 0.02
        order by sum(q.impressions) desc
        limit 5
      ) x
    ), '[]'::jsonb),
    'positions_4_to_20', coalesce((
      select jsonb_agg(x order by x.impressions desc)
      from (
        select
          q.query,
          coalesce(sum(q.clicks), 0)::bigint as clicks,
          coalesce(sum(q.impressions), 0)::bigint as impressions,
          case
            when coalesce(sum(q.impressions), 0) = 0 then null
            else sum(q.clicks)::numeric / nullif(sum(q.impressions), 0)
          end as ctr,
          case
            when coalesce(sum(q.impressions), 0) = 0 then null
            else sum(coalesce(q.position, 0) * coalesce(q.impressions, 0))
                 / nullif(sum(q.impressions), 0)
          end as position_avg
        from public.project_search_console_query_daily q
        where q.project_id = p_project_id
          and q.search_type = v_search_type
          and q.country = ''
          and q.device = ''
          and (p_date_from is null or q.metric_date >= p_date_from)
          and (p_date_to is null or q.metric_date <= p_date_to)
        group by q.query
        having (
          sum(coalesce(q.position, 0) * coalesce(q.impressions, 0))
          / nullif(sum(q.impressions), 0)
        ) between 4 and 20
        order by sum(q.impressions) desc
        limit 5
      ) x
    ), '[]'::jsonb)
  )
  into v_opportunities;

  -- Monitored page indexation summary (latest snapshot per page)
  select jsonb_build_object(
    'scope', 'monitored_pages_only',
    'monitored_pages', coalesce((
      select count(*)::int
      from public.project_site_pages sp
      where sp.project_id = p_project_id
        and sp.is_active = true
    ), 0),
    'inspected', coalesce((
      select count(distinct s.site_page_id)::int
      from public.project_site_page_index_snapshots s
      where s.project_id = p_project_id
        and s.site_page_id is not null
        and s.inspection_status = 'succeeded'
    ), 0),
    'indexed', coalesce((
      select count(*)::int
      from (
        select distinct on (s.site_page_id) s.internal_issue_category, s.verdict
        from public.project_site_page_index_snapshots s
        where s.project_id = p_project_id
          and s.site_page_id is not null
          and s.inspection_status = 'succeeded'
        order by s.site_page_id, s.inspection_date desc
      ) latest
      where latest.internal_issue_category = 'indexed'
         or lower(coalesce(latest.verdict, '')) in ('pass', 'partial')
    ), 0),
    'not_indexed', coalesce((
      select count(*)::int
      from (
        select distinct on (s.site_page_id) s.internal_issue_category
        from public.project_site_page_index_snapshots s
        where s.project_id = p_project_id
          and s.site_page_id is not null
          and s.inspection_status = 'succeeded'
        order by s.site_page_id, s.inspection_date desc
      ) latest
      where latest.internal_issue_category in (
        'not_indexed',
        'discovered_not_indexed',
        'crawled_not_indexed',
        'blocked_by_robots',
        'blocked_by_noindex',
        'fetch_error',
        'server_error',
        'soft_404',
        'redirect',
        'duplicate'
      )
    ), 0),
    'with_issues', coalesce((
      select count(*)::int
      from (
        select distinct on (s.site_page_id)
          s.internal_issue_category,
          jsonb_array_length(coalesce(s.issues, '[]'::jsonb)) as issue_count
        from public.project_site_page_index_snapshots s
        where s.project_id = p_project_id
          and s.site_page_id is not null
          and s.inspection_status = 'succeeded'
        order by s.site_page_id, s.inspection_date desc
      ) latest
      where latest.issue_count > 0
         or latest.internal_issue_category in (
           'canonical_mismatch',
           'rich_result_issue',
           'blocked_by_robots',
           'blocked_by_noindex',
           'fetch_error',
           'server_error',
           'soft_404'
         )
    ), 0),
    'not_inspected', greatest(
      coalesce((
        select count(*)::int
        from public.project_site_pages sp
        where sp.project_id = p_project_id
          and sp.is_active = true
      ), 0)
      - coalesce((
        select count(distinct s.site_page_id)::int
        from public.project_site_page_index_snapshots s
        where s.project_id = p_project_id
          and s.site_page_id is not null
          and s.inspection_status = 'succeeded'
      ), 0),
      0
    ),
    'last_inspection_at', (
      select max(s.inspection_date)
      from public.project_site_page_index_snapshots s
      where s.project_id = p_project_id
    )
  )
  into v_indexation;

  return jsonb_build_object(
    'project_id', p_project_id,
    'connected', coalesce(v_connected, false),
    'property', v_property,
    'search_type', v_search_type,
    'date_from', p_date_from,
    'date_to', p_date_to,
    'compare_date_from', p_compare_date_from,
    'compare_date_to', p_compare_date_to,
    'latest_metric_date', v_latest_metric_date,
    'last_synced_at', v_last_synced_at,
    'coverage_note',
      'Query–page rows from Search Console may be partial. Indexation covers monitored project pages only.',
    'current', coalesce(v_current, public.fn_gsc_metric_bundle(0, 0, 0)),
    'previous', v_previous,
    'timeseries', coalesce(v_timeseries, '[]'::jsonb),
    'top_queries', coalesce(v_queries, '[]'::jsonb),
    'top_pages', coalesce(v_pages, '[]'::jsonb),
    'opportunities', coalesce(v_opportunities, '{}'::jsonb),
    'indexation', coalesce(v_indexation, '{}'::jsonb)
  );
end;
$$;

