create or replace function public.fn_enqueue_site_page_inspection(
  p_project_id integer,
  p_site_page_id bigint default null,
  p_url text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_property_id bigint;
  v_url text;
  v_page_id bigint;
  v_queue_id bigint;
begin
  if p_project_id is null or not public.can_edit_project(p_project_id) then
    raise exception 'forbidden' using errcode = '42501';
  end if;

  select p.id
  into v_property_id
  from public.project_search_console_properties p
  where p.project_id = p_project_id
    and p.is_active = true
  order by p.updated_at desc
  limit 1;

  if v_property_id is null then
    raise exception 'Search Console property not connected';
  end if;

  if p_site_page_id is not null then
    select sp.id, coalesce(sp.canonical_url, sp.url)
    into v_page_id, v_url
    from public.project_site_pages sp
    where sp.id = p_site_page_id
      and sp.project_id = p_project_id
      and sp.is_active = true;
  elsif p_url is not null and length(trim(p_url)) > 0 then
    v_url := trim(p_url);
    select sp.id
    into v_page_id
    from public.project_site_pages sp
    where sp.project_id = p_project_id
      and sp.is_active = true
      and (sp.canonical_url = v_url or sp.url = v_url)
    limit 1;
  else
    raise exception 'site_page_id or url is required';
  end if;

  if v_url is null or length(v_url) = 0 then
    raise exception 'URL not found';
  end if;

  insert into public.project_search_console_inspect_queue (
    project_id,
    property_id,
    site_page_id,
    url,
    priority,
    status,
    requested_by_auth_user_id,
    scheduled_for
  )
  values (
    p_project_id,
    v_property_id,
    v_page_id,
    v_url,
    10,
    'queued',
    auth.uid(),
    now()
  )
  on conflict do nothing
  returning id into v_queue_id;

  if v_queue_id is null then
    select q.id into v_queue_id
    from public.project_search_console_inspect_queue q
    where q.property_id = v_property_id
      and q.url = v_url
      and q.status in ('queued', 'running')
    limit 1;
  end if;

  return jsonb_build_object(
    'ok', true,
    'queue_id', v_queue_id,
    'url', v_url,
    'site_page_id', v_page_id
  );
end;
$$;

