create or replace function public.fn_gsc_metric_bundle(
  p_clicks numeric,
  p_impressions numeric,
  p_position_weighted numeric
)
returns jsonb
language sql
immutable
as $$
  select jsonb_build_object(
    'clicks', coalesce(p_clicks, 0),
    'impressions', coalesce(p_impressions, 0),
    'ctr', case
      when coalesce(p_impressions, 0) <= 0 then null
      else p_clicks / nullif(p_impressions, 0)
    end,
    'position_avg', case
      when coalesce(p_impressions, 0) <= 0 then null
      else p_position_weighted / nullif(p_impressions, 0)
    end
  );
$$;

-- ---------------------------------------------------------------------------
-- 9) Integrations status (GA + GSC separately)
-- ---------------------------------------------------------------------------

create or replace function public.fn_get_project_google_integrations_status(
  p_project_id integer
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_oauth jsonb;
  v_ga jsonb;
  v_gsc jsonb;
begin
  if p_project_id is null or not public.can_edit_project(p_project_id) then
    raise exception 'forbidden' using errcode = '42501';
  end if;

  v_oauth := public.fn_get_project_google_oauth_status(p_project_id);

  begin
    select coalesce(
      (
        select jsonb_build_object(
          'connected', true,
          'ga_property_id', p.ga_property_id,
          'default_uri', p.default_uri,
          'updated_at', p.updated_at
        )
        from public.project_analytics_properties p
        where p.project_id = p_project_id
          and p.is_active = true
        order by p.updated_at desc
        limit 1
      ),
      jsonb_build_object('connected', false)
    )
    into v_ga;
  exception
    when undefined_table then
      v_ga := jsonb_build_object('connected', false);
  end;

  select coalesce(
    (
      select jsonb_build_object(
        'connected', true,
        'id', p.id,
        'property_url', p.property_url,
        'site_type', p.site_type,
        'last_synced_at', p.last_synced_at,
        'last_sync_status', p.last_sync_status,
        'last_sync_error', p.last_sync_error,
        'earliest_metric_date', p.earliest_metric_date,
        'latest_metric_date', p.latest_metric_date,
        'backfill_status', p.backfill_status,
        'backfill_progress', p.backfill_progress
      )
      from public.project_search_console_properties p
      where p.project_id = p_project_id
        and p.is_active = true
      order by p.updated_at desc
      limit 1
    ),
    jsonb_build_object('connected', false)
  )
  into v_gsc;

  return jsonb_build_object(
    'project_id', p_project_id,
    'oauth', v_oauth,
    'analytics', v_ga,
    'search_console', v_gsc
  );
end;
$$;

revoke all on function public.fn_get_project_google_integrations_status(integer) from public;
grant execute on function public.fn_get_project_google_integrations_status(integer) to authenticated;
grant execute on function public.fn_get_project_google_integrations_status(integer) to service_role;

